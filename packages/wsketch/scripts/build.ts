// Builds dist/: the compiled library plus the default model (the light one, ../../models).
//   bun scripts/build.ts          meta + compile + copy the model
//   bun scripts/build.ts meta     only regenerate src/meta.ts from models/shapes.json
import { copyFileSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { join } from "node:path"

const pkg = join(import.meta.dir, "..")
const models = join(pkg, "..", "..", "models")
const dist = join(pkg, "dist")

for (const name of ["shapes.int8.onnx", "shapes.json"]) {
  if (!existsSync(join(models, name))) {
    console.error(`missing ${join(models, name)}: export a model first (python -m wsketch.export)`)
    process.exit(1)
  }
}

// src/meta.ts: the description of the bundled model, so that it needs no extra request
const json = JSON.parse(readFileSync(join(models, "shapes.json"), "utf8"))
const meta = {
  classes: json.classes,
  reject_classes: json.reject_classes,
  thresholds: json.thresholds,
  input: { name: json.input.name, n_points: json.input.n_points },
}
writeFileSync(
  join(pkg, "src", "meta.ts"),
  `// Generated by scripts/build.ts from models/shapes.json, do not edit.\n` +
    `import type { ModelMeta } from "./types.js"\n\n` +
    `/** Description of the bundled model (wsketch/model.onnx). */\n` +
    `export const MODEL_META: ModelMeta = ${JSON.stringify(meta, null, 2)}\n`,
)
if (process.argv[2] === "meta") process.exit(0)

rmSync(dist, { recursive: true, force: true })
const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc")
const r = Bun.spawnSync([process.execPath, tsc, "-p", join(pkg, "tsconfig.build.json")], { stdout: "inherit", stderr: "inherit" })
if (r.exitCode !== 0) process.exit(r.exitCode ?? 1)
copyFileSync(join(models, "shapes.int8.onnx"), join(dist, "shapes.int8.onnx"))
copyFileSync(join(models, "shapes.json"), join(dist, "shapes.json"))
console.log("built dist/ with the model from models/")
